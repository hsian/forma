import { authenticatedPage } from './browser-auth.mjs';
import { openPreview } from './preview-helpers.mjs';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.PLAYWRIGHT_MODULE_ROOT ? resolve(process.env.PLAYWRIGHT_MODULE_ROOT, 'package.json') : import.meta.url);
const { chromium } = require('playwright');
if (!process.env.TEST_URL) throw Error('必须使用隔离测试服务器');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
let page = await authenticatedPage(browser, { viewport: { width: 1440, height: 1000 } });
const cookie = (await page.context().cookies(process.env.TEST_URL)).map(item => `${item.name}=${item.value}`).join('; ');
const result = JSON.parse(execFileSync(process.execPath, ['--import', 'tsx', 'scripts/add-account-select.ts', 'default-project'], { encoding: 'utf8', env: { ...process.env, FORMA_SESSION_COOKIE: cookie } }));
const editorPage = page;
async function leavePreview() { await page.close(); page = editorPage; await page.bringToFront(); }
const errors = []; page.on('pageerror', error => errors.push(error.message));
const button = name => page.getByRole('button', { name, exact: true });
const table = () => page.locator('.preview-page [data-preview-id="account-table"]');
const dialog = () => page.getByRole('dialog');
const group = id => dialog().locator(`[data-preview-id="${id}"]`);
const checkbox = (id, name) => group(id).getByRole('checkbox', { name, exact: true });
async function total(value) { if (value) await table().getByText(`共 ${value} 条`, { exact: true }).waitFor(); else await table().locator('.ant-empty-description').waitFor(); }
async function openView() { await button('☷ 自定义视图').click(); await dialog().waitFor(); }
try {
  await page.goto(process.env.TEST_URL);
  await page.locator('.studio[data-server-state="ready"]').waitFor();
  await page.locator('.page-tree-title>span').filter({ hasText: /^账套选择$/ }).click();
  await page.locator('.current-page-name').filter({ hasText: /^账套选择$/ }).waitFor();
  await page.screenshot({ path: 'test-results/account-select-editor.png', fullPage: true });
  assert.equal(await page.locator('.node[data-id="account-tabs"]').count(), 1);
  page = await openPreview(editorPage, errors);
  await total(9);
  assert.equal(await page.getByRole('combobox', { name: '停用注销状态筛选', exact: true }).count(), 0);
  await table().getByTitle('2', { exact: true }).click();
  assert.equal(await table().locator('tr.ant-table-row').count(), 4);
  await page.locator('.preview-page .prototype-tree .ant-tree-title').filter({ hasText: /^青禾村$/ }).click();
  await total(3);
  await page.getByRole('textbox', { name: '账套关键词', exact: true }).fill('不存在');
  await total(3);
  await button('查询').click(); await total(0);
  await button('重置').click(); await total(9);
  await page.getByRole('tab', { name: '停用注销账套', exact: true }).click(); await total(7);
  const status = page.locator('.preview-page .ant-select').filter({ has: page.getByRole('combobox', { name: '停用注销状态筛选', exact: true }) });
  await status.click(); await page.locator('.ant-select-item-option:visible').filter({ hasText: /^已停用$/ }).click(); await total(4);
  await button('重置').click(); await total(7);
  await openView();
  await checkbox('account-disabled-fields', '记账服务机构').uncheck();
  await button('取消').click();
  assert.equal(await table().getByRole('columnheader', { name: '记账服务机构', exact: true }).count(), 1);
  await openView();
  assert.equal(await checkbox('account-disabled-fields', '记账服务机构').isChecked(), true);
  await checkbox('account-disabled-fields', '记账服务机构').uncheck();
  await button('确定').click(); await dialog().waitFor({ state: 'hidden' });
  assert.equal(await table().getByRole('columnheader', { name: '记账服务机构', exact: true }).count(), 0);
  await openView(); await checkbox('account-disabled-fields', '全选').check(); await checkbox('account-disabled-fields', '全选').uncheck();
  await button('确定').click();
  await page.getByText('停用注销账套展示字段：请至少勾选一项必选字段', { exact: true }).waitFor();
  assert.equal(await dialog().isVisible(), true);
  await checkbox('account-disabled-fields', '账套名称').check();
  await page.screenshot({ path: 'test-results/account-select-dialog.png', fullPage: true });
  await button('确定').click(); await dialog().waitFor({ state: 'hidden' });
  assert.equal(await table().getByRole('columnheader').count(), 2, '只保留账套名称和操作');
  await table().getByRole('button', { name: '进入', exact: true }).first().click();
  await page.getByText('已选择账套。真实系统根据权限进入菜单，此原型暂不连接业务系统。', { exact: true }).waitFor();
  await page.getByRole('tab', { name: '正常使用账套', exact: true }).click(); await total(9);
  assert.equal(await table().getByRole('columnheader', { name: '记账服务机构', exact: true }).count(), 1);
  await page.screenshot({ path: 'test-results/account-select-preview.png', fullPage: true });
  await leavePreview();
  await page.locator('.node[data-id="account-table"]').click();
  await page.getByRole('textbox', { name: '第 1 列标题', exact: true }).fill('账套名称（编辑）');
  await button('编辑模拟数据（16 条）').click();
  await dialog().getByRole('textbox', { name: '数据 1 账套名称（编辑）', exact: true }).fill('测试账套');
  await button('完成').click();
  await dialog().waitFor({ state: 'hidden' });
  await page.keyboard.press('Control+s');
  await page.locator('[data-save-status="saved"]').waitFor();
  await page.reload(); await page.locator('.studio[data-server-state="ready"]').waitFor();
  page = await openPreview(editorPage, errors);
  assert.equal(await table().getByRole('columnheader', { name: '账套名称（编辑）', exact: true }).count(), 1);
  assert.ok((await table().innerText()).includes('测试账套'));
  const saved = await (await page.request.get(`${process.env.TEST_URL}/api/pages/${result.pageId}/document`)).json();
  assert.equal(saved.document.elements.find(e => e.id === 'account-table').table.rows.length, 16);
  assert.deepEqual(errors, []);
  console.log('PASS: 账套选择独立可编辑页面，页签/树/查询/重置/分页，弹窗取消与应用、必选校验，表格列和数据编辑保存及重载。');
} catch (error) {
  await page.screenshot({ path: 'test-results/account-select-failure.png', fullPage: true });
  console.error(errors); throw error;
} finally { await browser.close(); }
