import { authenticatedPage } from './browser-auth.mjs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { sketchFixture } from './fixtures/sketch.mjs';
const require = createRequire(process.env.PLAYWRIGHT_MODULE_ROOT ? resolve(process.env.PLAYWRIGHT_MODULE_ROOT, 'package.json') : import.meta.url);
const { chromium } = require('playwright');
if (!process.env.TEST_URL) throw Error('必须使用隔离测试服务器');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH });
const page = await authenticatedPage(browser, { viewport: { width: 1600, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const button = name => page.getByRole('button', { name, exact: true });
const tab = name => page.getByRole('tab', { name, exact: true });
async function menu(name) { await button('页面操作 用户管理').click(); await page.getByRole('menuitem', { name, exact: true }).click(); }
try {
  await page.goto(`${process.env.TEST_URL}/design`);
  await page.locator('.studio[data-server-state="ready"]').waitFor();
  await page.locator('.prototype-page-tree').waitFor();
  assert.equal(await page.getByRole('tablist', { name: '页面交付物' }).count(), 0);
  const before = (await (await page.request.get(`${process.env.TEST_URL}/api/pages/default-page/document`)).json()).document;
  await menu('需要 UI 设计');
  await tab('原型').waitFor();
  for (const width of [1600, 1440, 1000, 760]) {
    await page.setViewportSize({ width, height: 1000 });
    await tab('原型').click();
    await page.waitForFunction(() => !document.querySelector('.editor-layout').classList.contains('viewing-ui-design'));
    const prototypeWidth = (await page.locator('.left-panel').boundingBox()).width;
    await button('查看 UI 设计稿 用户管理').click();
    await page.waitForFunction(() => document.querySelector('.editor-layout').classList.contains('viewing-ui-design'));
    assert.equal((await page.locator('.left-panel').boundingBox()).width, prototypeWidth, `sidebar width stays the same at ${width}px`);
  }
  await page.setViewportSize({ width: 1600, height: 1000 });
  await button('查看 UI 设计稿 用户管理').click();
  await page.getByText('等待 UI 设计', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/page-design-empty.png', animations: 'disabled' });
  await page.locator('.ui-design-empty').getByRole('button', { name: '上传 Sketch', exact: true }).click();
  await page.getByLabel('Sketch 文件', { exact: true }).setInputFiles({ name: '界面设计.sketch', mimeType: 'application/octet-stream', buffer: sketchFixture() });
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === '关联到页面' && !button.disabled));
  await button('关联到页面').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.locator('.ui-design-board').getByText('导入的设计文字', { exact: true }).waitFor();
  const scene = page.locator('.ui-design-scene');
  const zoom = async () => Number(await scene.getAttribute('data-zoom'));
  await button('设计稿原始大小').click();
  await page.waitForFunction(() => Number(document.querySelector('.ui-design-scene')?.dataset.zoom) === 1);
  await button('放大设计稿').click();
  assert.ok(await zoom() > 1);
  await button('缩小设计稿').click();
  assert.equal(await zoom(), 1);
  const canvas = page.getByRole('region', { name: '设计稿画布', exact: true });
  const bounds = await canvas.boundingBox();
  const anchor = { x: bounds.x + bounds.width / 2 + 50, y: bounds.y + bounds.height / 2 };
  const rectBefore = await scene.boundingBox();
  await page.mouse.move(anchor.x, anchor.y);
  await page.mouse.wheel(0, -300);
  await page.waitForFunction(() => Number(document.querySelector('.ui-design-scene')?.dataset.zoom) > 1);
  const wheelZoom = await zoom();
  assert.ok(wheelZoom <= 1.05 + 1e-9, 'a large wheel event increases zoom by at most 5%');
  const rectAfter = await scene.boundingBox();
  assert.ok(Math.abs((anchor.x - rectBefore.x) - (anchor.x - rectAfter.x) / wheelZoom) < 2, 'wheel zoom keeps the point under the cursor fixed');
  await page.mouse.down(); await page.mouse.move(anchor.x + 80, anchor.y + 45, { steps: 5 }); await page.mouse.up();
  const dragged = await scene.boundingBox();
  assert.ok(Math.abs(dragged.x - rectAfter.x - 80) < 2);
  assert.ok(Math.abs(dragged.y - rectAfter.y - 45) < 2);
  await button('设计稿适应窗口').click();
  const fitted = await scene.boundingBox();
  assert.ok(fitted.width <= bounds.width && fitted.height <= bounds.height, 'fit uses the actual viewport dimensions');
  await canvas.focus(); await page.keyboard.press('1');
  assert.equal(await zoom(), 1);
  await page.keyboard.press('+');
  assert.ok(await zoom() > 1);
  await page.keyboard.press('0');
  await page.screenshot({ path: 'test-results/page-design-preview.png', animations: 'disabled' });
  assert.equal((await (await page.request.get(`${process.env.TEST_URL}/api/projects/default-project/pages`)).json()).pages.length, 1);
  assert.deepEqual((await (await page.request.get(`${process.env.TEST_URL}/api/pages/default-page/document`)).json()).document, before);
  await tab('原型').click();
  await page.locator('.current-page-name').getByText('用户管理', { exact: true }).waitFor();
  await page.reload(); await page.locator('.studio[data-server-state="ready"]').waitFor();
  await button('查看 UI 设计稿 用户管理').click();
  await page.locator('.ui-design-board').getByText('导入的设计文字', { exact: true }).waitFor();
  await menu('设为无需 UI 设计');
  await page.getByRole('tablist', { name: '页面交付物' }).waitFor({ state: 'hidden' });
  assert.equal(await button('查看 UI 设计稿 用户管理').count(), 0);
  await menu('需要 UI 设计');
  await button('查看 UI 设计稿 用户管理').click();
  await page.locator('.ui-design-board').getByText('导入的设计文字', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
