import {authenticatedPage} from './browser-auth.mjs';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
import {sketchFixture} from './fixtures/sketch.mjs';
const require=createRequire(process.env.PLAYWRIGHT_MODULE_ROOT?resolve(process.env.PLAYWRIGHT_MODULE_ROOT,'package.json'):import.meta.url);
const {chromium}=require('playwright');
if(!process.env.TEST_URL)throw Error('必须使用隔离测试服务器');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH});
const page=await authenticatedPage(browser,{viewport:{width:1600,height:1000}});
const base=process.env.TEST_URL, errors=[];page.on('pageerror',error=>errors.push(error.message));
const button=name=>page.getByRole('button',{name,exact:true});
try{
  await page.goto(`${base}/design`);await page.locator('.studio[data-server-state="ready"]').waitFor();
  const original=(await(await page.request.get(`${base}/api/pages/default-page/document`)).json()).document;
  const layers=[20,144].map((x,index)=>({_class:'rectangle',do_objectID:`button-${index}`,name:`按钮${index===0?'一':'二'}`,frame:{x,y:20,width:100,height:40},style:{fills:[{isEnabled:true,fillType:0,color:{red:1,green:0,blue:0,alpha:1}}]}}));
  const upload=await page.request.post(`${base}/api/projects/default-project/sketch`,{headers:{'Content-Type':'application/octet-stream'},data:sketchFixture(layers)});
  assert.equal(upload.ok(),true,await upload.text());
  const imported=await page.request.post(`${base}/api/projects/default-project/sketch/${(await upload.json()).token}/import`,{data:{pageId:'p',boardId:'board',targetPageId:'default-page',acceptWarnings:true}});
  assert.equal(imported.ok(),true,await imported.text());
  const designId=(await imported.json()).board.id;
  const source=(await(await page.request.get(`${base}/api/pages/default-page/design/${designId}`)).json()).document;
  await button('刷新页面列表').click();await button('查看 UI 设计稿 用户管理').click();
  await page.locator('.ui-design-board').waitFor();await button('AI 问设计').click();
  const panel=page.getByRole('region',{name:'设计稿 AI 助手'});
  await page.locator('#design-ai-assistant-panel').waitFor();
  await button('设计稿原始大小').click();
  const scene=await page.locator('.ui-design-scene').boundingBox();
  await page.mouse.click(scene.x+50,scene.y+40);
  await page.keyboard.down('Shift');await page.mouse.click(scene.x+170,scene.y+40);await page.keyboard.up('Shift');
  await page.locator('.design-ai-scope').getByText('已选 2 个图层：按钮一、按钮二',{exact:true}).waitFor();
  assert.equal(await page.locator('.design-layer-selection').count(),2);
  const input=page.getByRole('textbox',{name:'设计稿 AI 问题',exact:true});
  await input.fill('这两个按钮间距多少，填充颜色是什么？');await button('发送设计稿 AI 问题').click();
  await page.locator('#design-ai-assistant-panel .ai-inline-notice').getByText(/水平间距 24px；填充 #ff0000/).waitFor();
  await button('展开设计稿 AI 对话').click();
  await page.getByRole('log',{name:'设计稿 AI 对话记录'}).getByText(/水平间距 24px；填充 #ff0000/).waitFor();
  assert.deepEqual((await(await page.request.get(`${base}/api/pages/default-page/document`)).json()).document,original);
  assert.deepEqual((await(await page.request.get(`${base}/api/pages/default-page/design/${designId}`)).json()).document,source);
  await page.screenshot({path:'test-results/design-ai.png',animations:'disabled'});
  await page.keyboard.press('Control+Backquote');assert.equal(await page.locator('#design-ai-assistant-panel').isVisible(),false);
  await page.keyboard.press('Control+Backquote');assert.equal(await page.locator('#design-ai-assistant-panel').isVisible(),true);
  await page.reload();await page.locator('.studio[data-server-state="ready"]').waitFor();
  await button('查看 UI 设计稿 用户管理').click();await page.locator('.ui-design-board').waitFor();await button('AI 问设计').click();await button('展开设计稿 AI 对话').click();
  await page.getByRole('log',{name:'设计稿 AI 对话记录'}).getByText(/水平间距 24px；填充 #ff0000/).waitFor();
  assert.deepEqual(errors,[]);
}catch(error){await page.screenshot({path:'test-results/design-ai-failure.png',animations:'disabled'});console.log('Design AI browser diagnostics',JSON.stringify({errors,viewers:await page.locator('.ui-design-viewer').count(),buttons:await page.locator('[aria-label="设计稿原始大小"]').evaluateAll(elements=>elements.map(element=>element.outerHTML))}));throw error;}finally{await browser.close();}
