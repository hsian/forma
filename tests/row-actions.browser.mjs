import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { openPreview } from './preview-helpers.mjs';
const require = createRequire(process.env.PLAYWRIGHT_MODULE_ROOT ? resolve(process.env.PLAYWRIGHT_MODULE_ROOT, 'package.json') : import.meta.url);
const { chromium } = require('playwright');
if (!process.env.TEST_URL) throw Error('必须使用隔离测试服务器');
const fixture = JSON.parse(execFileSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', "import {rowActionDocument} from './tests/fixtures/row-actions.ts';console.log(JSON.stringify(rowActionDocument()))"], { encoding: 'utf8' }));
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const editor = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
const errors = []; editor.on('pageerror', error => errors.push(error.message));
const base = process.env.TEST_URL;
const read = async () => (await editor.request.get(`${base}/api/pages/default-page/document`)).json();
let preview;
try {
  const existing = await read();
  const saved = await editor.request.put(`${base}/api/pages/default-page/document`, { data: { revision: existing.revision, document: fixture } });
  assert.equal(saved.ok(), true, await saved.text());
  await editor.goto(base); await editor.getByText('本地服务已连接', { exact: true }).waitFor();
  await editor.locator('.node[data-id="records"]').click();
  await editor.getByRole('textbox', { name: '行操作 1 文字', exact: true }).waitFor();
  assert.equal(await editor.getByRole('textbox', { name: /^行操作 \d+ 文字$/ }).count(), 3);
  // Each row action points at an ordinary, editable dialog.
  await editor.getByRole('button', { name: '编辑行操作弹窗', exact: true }).first().click();
  await editor.locator('.node[data-id="row-name"]').click();
  await editor.getByRole('combobox', { name: '绑定当前行字段', exact: true }).waitFor();
  await editor.locator('.dialog-edit-banner').getByRole('button', { name: '返回页面', exact: true }).click();
  preview = await openPreview(editor, errors);
  const table = preview.locator('[data-preview-id="records"]');
  const other = preview.locator('[data-preview-id="other-records"]');
  const dialog = preview.getByRole('dialog');
  const button = name => preview.getByRole('button', { name, exact: true });
  await table.getByTitle('2', { exact: true }).click();
  await table.getByRole('row').filter({ hasText: 'Delta' }).getByRole('button', { name: '修改资料', exact: true }).click();
  await dialog.getByText('当前记录：Delta', { exact: true }).waitFor();
  assert.equal(await dialog.getByRole('textbox', { name: '记录名称', exact: true }).inputValue(), 'Delta');
  await dialog.getByRole('textbox', { name: '记录名称', exact: true }).fill('未保存的修改');
  await button('取消修改').click(); await dialog.waitFor({ state: 'hidden' });
  assert.ok((await table.innerText()).includes('Delta'));
  // Filtering must retain the source index rather than treating this as the first row.
  await preview.getByRole('textbox', { name: '筛选记录', exact: true }).fill('Delta');
  await table.getByRole('button', { name: '修改资料', exact: true }).click();
  await dialog.getByRole('textbox', { name: '记录名称', exact: true }).fill('');
  await button('保存修改').click(); await dialog.getByText('请输入记录名称', { exact: true }).waitFor();
  await dialog.getByRole('textbox', { name: '记录名称', exact: true }).fill('Delta 已修改');
  await dialog.locator('.ant-select').click();
  await preview.locator('.ant-select-item-option:visible').filter({ hasText: /^归档$/ }).click();
  await button('保存修改').click(); await dialog.waitFor({ state: 'hidden' });
  await table.getByText('Delta 已修改', { exact: true }).waitFor();
  await table.getByText('archived', { exact: true }).waitFor();
  await table.getByRole('button', { name: '说明', exact: true }).click();
  await preview.getByText('选中了 Delta 已修改', { exact: true }).waitFor();
  // A different table reuses the same dialog, with its own row context and draft.
  await other.getByRole('button', { name: '编辑商品', exact: true }).click();
  await dialog.getByText('当前记录：商品甲', { exact: true }).waitFor();
  assert.equal(await dialog.getByRole('textbox', { name: '记录名称', exact: true }).inputValue(), '商品甲');
  await preview.screenshot({ path: 'test-results/row-actions-dialog.png', fullPage: true });
  await button('取消修改').click(); await dialog.waitFor({ state: 'hidden' });
  await other.getByRole('button', { name: '移除商品', exact: true }).click();
  await dialog.getByText('是否移除 商品甲？', { exact: true }).waitFor();
  await button('取消移除').click(); await dialog.waitFor({ state: 'hidden' });
  await other.getByText('商品甲', { exact: true }).waitFor();
  await other.getByRole('button', { name: '移除商品', exact: true }).click();
  await button('确认移除').click(); await dialog.waitFor({ state: 'hidden' });
  await other.locator('.ant-empty-description').waitFor();
  await table.getByText('Delta 已修改', { exact: true }).waitFor();
  assert.deepEqual((await read()).document, fixture, '预览修改不能写回原型文档');
  await preview.reload(); await preview.locator('.preview-page').waitFor();
  await other.getByText('商品甲', { exact: true }).waitFor();
  await table.getByTitle('2', { exact: true }).click(); await table.getByText('Delta', { exact: true }).waitFor();
  await preview.close(); preview = null;
  // New dialogs created from row actions are part of the same undoable document edit.
  await editor.locator('.node[data-id="records"]').click();
  await editor.getByRole('button', { name: '添加行操作', exact: true }).click();
  await editor.getByRole('textbox', { name: '行操作 4 文字', exact: true }).fill('审核');
  await editor.getByRole('button', { name: '新建并编辑弹窗', exact: true }).last().click();
  await editor.getByRole('textbox', { name: '弹窗标题', exact: true }).fill('审核 {{row.name}}');
  await editor.locator('.dialog-edit-banner').getByRole('button', { name: '返回页面', exact: true }).click();
  await editor.keyboard.press('Control+s'); await editor.locator('[data-save-status="saved"]').waitFor();
  const modified = (await read()).document;
  const action = modified.elements.find(e => e.id === 'records').table.rowActions.at(-1);
  assert.equal(action.label, '审核'); assert.equal(modified.dialogs.find(d => d.id === action.modalId).title, '审核 {{row.name}}');
  await editor.reload(); await editor.getByText('本地服务已连接', { exact: true }).waitFor();
  await editor.locator('.node[data-id="records"]').click();
  assert.equal(await editor.getByRole('textbox', { name: '行操作 4 文字', exact: true }).inputValue(), '审核');
  assert.deepEqual(errors, []);
  console.log('PASS: 多行操作、任意弹窗、分页筛选定位、字段回填及校验、取消隔离、更新删除模拟行、多表复用、刷新恢复、手工编辑与保存。');
} catch (error) { await (preview || editor).screenshot({ path: 'test-results/row-actions-failure.png', fullPage: true }); throw error; }
finally { await browser.close(); }
