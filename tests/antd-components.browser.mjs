import { authenticatedPage } from './browser-auth.mjs';
import { openPreview } from './preview-helpers.mjs';
import { tsImport } from 'tsx/esm/api';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const { antdKinds } = await tsImport('../shared/antd-catalog.ts', import.meta.url);
const { makeElement } = await tsImport('../shared/model.ts', import.meta.url);
const require = createRequire(process.env.PLAYWRIGHT_MODULE_ROOT ? resolve(process.env.PLAYWRIGHT_MODULE_ROOT, 'package.json') : import.meta.url);
const { chromium } = require('playwright');
if (!process.env.TEST_URL) throw Error('必须使用隔离测试服务器');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const page = await authenticatedPage(browser, { viewport: { width: 1600, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const base = process.env.TEST_URL;
const read = async () => (await (await page.request.get(`${base}/api/pages/default-page/document`)).json()).document;
const button = name => page.getByRole('button', { name, exact: true });
let preview;
try {
  const initial = await (await page.request.get(`${base}/api/pages/default-page/document`)).json();
  const all = { width: 1600, height: 12000, background: '#ffffff', elements: antdKinds.map((kind, index) => ({ ...makeElement(kind, 24 + index % 3 * 520, 24 + Math.floor(index / 3) * 420), id: 'catalog-' + kind, width: Math.min(makeElement(kind).width, 480) })) };
  const saved = await page.request.put(`${base}/api/pages/default-page/document`, { data: { revision: initial.revision, document: all } });
  assert.equal(saved.status(), 200, await saved.text());
  await page.goto(`${base}/design`); await page.locator('.studio[data-server-state="ready"]').waitFor();
  assert.equal(await page.locator('.artboard .node').count(), antdKinds.length);
  assert.equal(await page.getByText('组件暂不可用', { exact: true }).count(), 0);
  await button('元素').click();
  assert.equal(await page.locator('.element-card').count(), antdKinds.length + 4);
  await page.locator('.component-group').filter({ has: page.locator('summary').getByText('通用', { exact: true }) }).locator('summary').click();
  assert.equal(await page.locator('.element-card[data-element-kind="button"]').isVisible(), false);
  await page.getByPlaceholder('搜索元素', { exact: true }).fill('Card');
  assert.equal(await page.locator('.element-card').count(), 1);
  await button('卡片').click();
  const cardId = await page.locator('.node-selected').getAttribute('data-id');
  await page.getByRole('textbox', { name: 'Card 卡片标题', exact: true }).fill('订单信息');
  await page.getByRole('textbox', { name: 'Card 内容', exact: true }).fill('这是可编辑的卡片正文');
  await page.locator('[data-save-status="saved"]').waitFor();
  assert.equal((await read()).elements.find(e => e.id === cardId).component.title, '订单信息');
  assert.equal((await read()).elements.find(e => e.id === 'catalog-card').component.title, '卡片标题');
  await button('复制选中元素 Ctrl+D').click();
  const cloneId = await page.locator('.node-selected').getAttribute('data-id');
  await page.getByRole('textbox', { name: 'Card 卡片标题', exact: true }).fill('独立副本');
  await page.locator('[data-save-status="saved"]').waitFor();
  assert.equal((await read()).elements.find(e => e.id === cardId).component.title, '订单信息');
  assert.equal((await read()).elements.find(e => e.id === cloneId).component.title, '独立副本');
  await button('撤销 Ctrl+Z').click();
  await page.locator('[data-save-status="saved"]').waitFor();
  assert.equal((await read()).elements.find(e => e.id === cloneId).component.title, '订单信息');
  await page.getByPlaceholder('搜索元素', { exact: true }).fill('Radio');
  await button('单选框组').click();
  const radioId = await page.locator('.node-selected').getAttribute('data-id');
  const radioDefault = page.locator('.ant-select').filter({ has: page.getByRole('combobox', { name: 'Radio 默认选中项', exact: true }) });
  await radioDefault.click();
  await page.locator('.ant-select-dropdown:visible').getByText('选项二', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Radio 条目 2 名称', exact: true }).fill('高级用户');
  assert.ok((await radioDefault.innerText()).includes('高级用户'), '默认选中项跟随稳定条目，使用名称选择');
  await page.locator('[data-save-status="saved"]').waitFor();
  assert.equal((await read()).elements.find(e => e.id === radioId).component.value, 'two');
  await page.screenshot({ path: 'test-results/antd-radio-properties.png' });
  await page.reload(); await page.locator('.studio[data-server-state="ready"]').waitFor();
  assert.equal(await page.locator('.artboard .node').count(), antdKinds.length + 3);
  preview = await openPreview(page, errors);
  assert.equal(await preview.locator('.preview-page>[data-preview-id]').count(), antdKinds.length + 3);
  assert.equal(await preview.locator(`[data-preview-id="${radioId}"] input[value="two"]`).isChecked(), true);
  assert.equal(await preview.getByText('组件暂不可用', { exact: true }).count(), 0);
  const control = kind => preview.locator(`[data-preview-id="catalog-${kind}"]`);
  await control('radio').getByText('选项二', { exact: true }).click();
  assert.equal(await control('radio').locator('input[value="two"]').isChecked(), true);
  await control('inputNumber').getByRole('spinbutton').fill('42');
  assert.equal(await control('inputNumber').getByRole('spinbutton').inputValue(), '42');
  await control('datePicker').getByRole('textbox').fill('2026-11-15');
  await control('datePicker').getByRole('textbox').press('Enter');
  assert.equal(await control('datePicker').getByRole('textbox').inputValue(), '2026-11-15');
  await control('cascader').locator('.ant-select-selector').click();
  await preview.locator('.ant-cascader-dropdown:visible').getByText('浙江', { exact: true }).click();
  await preview.locator('.ant-cascader-dropdown:visible').getByText('杭州', { exact: true }).click();
  await control('collapse').getByText('选项二', { exact: true }).click();
  await control('collapse').getByText('第二项的说明', { exact: true }).waitFor();
  await control('dropdown').getByRole('button').click();
  await preview.locator('.ant-dropdown:visible').getByRole('menuitem', { name: '选项二', exact: true }).click();
  await control('form').getByRole('button', { name: '提交', exact: true }).click();
  await control('form').getByText('请输入选项一', { exact: true }).waitFor();
  for (const input of await control('form').getByRole('textbox').all()) await input.fill('模拟数据');
  await control('form').getByRole('button', { name: '提交', exact: true }).click();
  await preview.getByText('模拟表单提交成功', { exact: true }).waitFor();
  let uploadRequests = 0;
  preview.on('request', request => { if (request.method() === 'POST' && !request.url().includes('/api/')) uploadRequests++; });
  await control('upload').locator('input[type="file"]').setInputFiles({ name: 'example.txt', mimeType: 'text/plain', buffer: Buffer.from('prototype data') });
  await control('upload').getByText('example.txt', { exact: true }).waitFor();
  assert.equal(uploadRequests, 0);
  await control('modal').getByRole('button').click();
  await preview.getByRole('dialog').getByText('在这里填写对话框内容。', { exact: true }).waitFor();
  await preview.getByRole('dialog').getByRole('button', { name: '确定', exact: true }).click();
  await control('drawer').getByRole('button').click();
  await preview.getByRole('dialog').getByText('在这里填写抽屉内容。', { exact: true }).waitFor();
  await preview.locator('.ant-drawer:visible .ant-drawer-close').click();
  await control('popconfirm').getByRole('button').click();
  await preview.getByRole('button', { name: '确定', exact: true }).click();
  await preview.getByText('已确认（原型演示）', { exact: true }).waitFor();
  const beforeRuntime = await read();
  assert.equal(beforeRuntime.elements.find(e => e.kind === 'inputNumber').component.value, 0);
  assert.equal(beforeRuntime.elements.find(e => e.kind === 'datePicker').component.value, '');
  await preview.close(); preview = null;
  assert.deepEqual(errors, []);
  console.log(`PASS: ${antdKinds.length} 个 Ant Design 组件完整渲染、分类搜索、专属属性、复制/撤销/重载持久化；单选/数字/日期/级联/菜单/折叠/表单/模拟上传/弹窗/抽屉/确认交互。`);
} catch (error) { await (preview || page).screenshot({ path: 'test-results/antd-components-failure.png' }); console.error(errors); throw error; }
finally { await browser.close(); }
