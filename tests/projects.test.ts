import { test } from 'node:test';
import assert from 'node:assert/strict';
import Fastify from 'fastify';
import { openDatabase } from '../server/db';
import { createRepository, defaultPageId, defaultProjectId } from '../server/db/repository';
import { registerApi } from '../server/api';
import { makeElement } from '../shared/model';

test('项目和多级页面 CRUD、跨项目限制、循环检查、复制隔离与级联删除', async () => {
  const connection = openDatabase(':memory:');
  const repository = createRepository(connection.db); repository.initialize();
  const app = Fastify(); registerApi(app, repository);
  app.addHook('onClose', async () => connection.close());
  const request = async (method: 'POST' | 'PATCH' | 'DELETE', url: string, payload?: Record<string, unknown>) => app.inject({ method, url, ...(payload === undefined ? {} : { payload }) });
  try {
    const created = (await request('POST', '/api/projects', { name: '业务项目' })).json();
    const projectId = created.project.id, rootId = created.page.id;
    assert.deepEqual(repository.readDocument(rootId)?.document.elements, []);
    const child = (await request('POST', `/api/projects/${projectId}/pages`, { name: '详情', parentId: rootId })).json();
    const grandchild = (await request('POST', `/api/projects/${projectId}/pages`, { name: '权限', parentId: child.id })).json();
    assert.equal((await request('PATCH', `/api/pages/${rootId}`, { parentId: grandchild.id })).statusCode, 400);
    assert.equal((await request('POST', `/api/projects/${projectId}/pages`, { name: '非法父级', parentId: defaultPageId })).statusCode, 400);
    assert.equal((await request('PATCH', `/api/pages/${child.id}`, { parentId: defaultPageId })).statusCode, 400);
    assert.equal((await request('DELETE', `/api/pages/${rootId}`)).statusCode, 409, 'cannot delete all pages through their parent');
    const document = repository.readDocument(child.id)!;
    document.document.elements.push({ ...makeElement('text'), text: '详情内容' });
    repository.saveDocument(child.id, 0, document.document);
    const duplicate = (await request('POST', `/api/pages/${child.id}/duplicate`)).json();
    assert.equal(duplicate.parentId, rootId);
    assert.deepEqual(repository.readDocument(duplicate.id)?.document, repository.readDocument(child.id)?.document);
    const copy = repository.readDocument(duplicate.id)!;
    copy.document.elements[0].text = '副本内容';
    repository.saveDocument(duplicate.id, 0, copy.document);
    assert.equal(repository.readDocument(child.id)!.document.elements[0].text, '详情内容');
    await request('PATCH', `/api/pages/${grandchild.id}`, { parentId: null });
    assert.equal(repository.listPages(projectId).find(page => page.id === grandchild.id)?.parentId, null);
    await request('PATCH', `/api/pages/${grandchild.id}`, { order: 'up' });
    assert.equal(repository.listPages(projectId).filter(page => !page.parentId)[0].id, grandchild.id);
    await request('PATCH', `/api/pages/${grandchild.id}`, { name: '独立权限页' });
    await request('PATCH', `/api/projects/${projectId}`, { name: '业务项目二' });
    assert.equal(repository.bootstrap(grandchild.id).page.name, '独立权限页');
    assert.equal(repository.bootstrap(grandchild.id).project.name, '业务项目二');
    const deleteResponse = await request('DELETE', `/api/pages/${rootId}`);
    assert.equal(deleteResponse.statusCode, 200, deleteResponse.body);
    const deleted = deleteResponse.json();
    assert.deepEqual(new Set(deleted.deletedIds), new Set([rootId, child.id, duplicate.id]));
    assert.equal(repository.readDocument(child.id), null);
    assert.equal(deleted.fallbackPageId, grandchild.id);
    assert.equal(repository.bootstrap(child.id).page.id, defaultPageId, 'deleted selection falls back to a valid page');
    const disposable = repository.createProject('待删除项目');
    const disposableChild = repository.createPage(disposable.project.id, '项目内子页', disposable.page.id);
    assert.equal((await request('DELETE', `/api/projects/${disposable.project.id}`)).statusCode, 200);
    assert.equal(repository.readDocument(disposable.page.id), null);
    assert.equal(repository.readDocument(disposableChild.id), null);
    assert.equal((await request('DELETE', `/api/projects/${defaultProjectId}`)).statusCode, 200);
    repository.initialize();
    assert.deepEqual(repository.listProjects().map(project => project.id), [projectId], 'startup must not resurrect deleted default projects');
    assert.equal((await request('DELETE', `/api/projects/${projectId}`)).statusCode, 409);
    assert.equal((await request('POST', '/api/projects', { name: '   ' })).statusCode, 400);
    assert.equal((await request('PATCH', '/api/pages/missing', { name: '不存在' })).statusCode, 404);
  } finally { await app.close(); }
});
