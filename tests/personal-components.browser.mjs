import { authenticatedPage } from './browser-auth.mjs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.PLAYWRIGHT_MODULE_ROOT ? resolve(process.env.PLAYWRIGHT_MODULE_ROOT, 'package.json') : import.meta.url);
const { chromium } = require('playwright');
if (!process.env.TEST_URL) throw Error('必须使用隔离测试服务器');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const page = await authenticatedPage(browser, { viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const base = process.env.TEST_URL;
try {
  await page.goto(`${base}/design`);
  await page.locator('.studio[data-server-state="ready"]').waitFor();
  await page.getByRole('button', { name: '图层', exact: false }).first().click();
  for (const [index, name] of ['姓名搜索', '状态筛选', '查询按钮'].entries()) await page.locator('.layer-name').filter({ hasText: name }).click({ modifiers: index ? ['Shift'] : [] });
  assert.equal(await page.locator('.node-selected').count(), 3);
  await page.getByRole('button', { name: '保存到我的组件', exact: true }).click();
  await page.getByRole('textbox', { name: '组件名称', exact: true }).fill('通用筛选表单');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '插入组件 通用筛选表单', exact: true }).waitFor();
  let items = (await (await page.request.get(`${base}/api/me/components`)).json()).components;
  assert.equal(items.length, 1); assert.equal(items[0].document.elements.length, 3);
  const template = structuredClone(items[0]);
  const created = await page.request.post(`${base}/api/projects`, { data: { name: '组件复用目标项目' } });
  assert.ok(created.ok(), await created.text());
  const project = await created.json();
  await page.goto(`${base}/design?projectId=${project.project.id}&pageId=${project.page.id}`);
  await page.locator('.studio[data-server-state="ready"]').waitFor();
  await page.getByRole('button', { name: '元素', exact: true }).click();
  await page.getByRole('button', { name: '我的组件', exact: true }).click();
  const before = await page.locator('.node').count();
  await page.getByRole('button', { name: '插入组件 通用筛选表单', exact: true }).click();
  assert.equal(await page.locator('.node').count(), before + 3);
  const ids = await page.locator('.node-selected').evaluateAll(nodes => nodes.map(node => node.dataset.id));
  await page.getByRole('button', { name: '插入组件 通用筛选表单', exact: true }).click();
  assert.equal(await page.locator('.node').count(), before + 6);
  const otherIds = await page.locator('.node-selected').evaluateAll(nodes => nodes.map(node => node.dataset.id));
  assert.ok(!ids.some(id => otherIds.includes(id)));
  await page.getByRole('button', { name: '撤销 Ctrl+Z', exact: true }).click();
  assert.equal(await page.locator('.node').count(), before + 3);
  await page.getByRole('button', { name: '重做 Ctrl+Shift+Z', exact: true }).click();
  assert.equal(await page.locator('.node').count(), before + 6);
  await page.getByRole('button', { name: '修改组件 通用筛选表单', exact: true }).click();
  await page.getByRole('menuitem', { name: '重命名', exact: true }).click();
  await page.getByRole('textbox', { name: '组件名称', exact: true }).fill('我的筛选表单');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '插入组件 我的筛选表单', exact: true }).waitFor();
  // Drag inserts the full selection at the drop point.
  const beforeDrag = await page.locator('.node').count();
  await page.getByRole('button', { name: '插入组件 我的筛选表单', exact: true }).dragTo(page.locator('.artboard'), { targetPosition: { x: 250, y: 100 } });
  assert.equal(await page.locator('.node').count(), beforeDrag + 3);
  await page.getByRole('button', { name: '图层', exact: false }).first().click();
  await page.locator('.layer-name').filter({ hasText: '查询按钮' }).last().click();
  await page.getByRole('spinbutton', { name: 'W', exact: true }).fill('180');
  await page.getByRole('spinbutton', { name: 'W', exact: true }).press('Tab');
  await page.getByRole('button', { name: '元素', exact: true }).click();
  await page.getByRole('button', { name: '修改组件 我的筛选表单', exact: true }).click();
  await page.getByRole('menuitem', { name: '用选中元素更新', exact: true }).click();
  await page.getByRole('button', { name: '更新组件', exact: true }).click();
  await page.waitForFunction(async () => (await (await fetch('/api/me/components')).json()).components[0].document.elements.length === 1);
  items = (await (await page.request.get(`${base}/api/me/components`)).json()).components;
  assert.equal(items[0].document.elements[0].width, 180);
  assert.equal(template.document.elements.length, 3);
  await page.locator('[data-save-status="saved"]').waitFor();
  await page.reload();
  await page.locator('.studio[data-server-state="ready"]').waitFor();
  assert.equal(await page.locator('.node').count(), beforeDrag + 3, '刷新后保留已插入的副本');
  await page.getByRole('button', { name: '元素', exact: true }).click();
  await page.getByRole('button', { name: '我的组件', exact: true }).click();
  await page.screenshot({ path: 'test-results/personal-components.png', fullPage: true });
  await page.getByRole('button', { name: '删除组件 我的筛选表单', exact: true }).click();
  await page.getByRole('button', { name: '删除', exact: true }).click();
  await page.getByText('选中画布上的元素，保存为你的第一个组件').waitFor();
  assert.equal(await page.locator('.node').count(), beforeDrag + 3);
  assert.deepEqual(errors, []);
  console.log('个人组件浏览器验证通过：选区保存、跨项目复用、点击和拖入、独立副本、撤销重做、更新、重命名、刷新及删除');
} finally { await browser.close(); }
